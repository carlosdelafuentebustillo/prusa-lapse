import os
import sys
import unittest

# Ensure orcaslicer-plugin root is in sys.path
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

from prusalapse.injector import (
    is_binary_bgcode,
    parse_bed_boundaries,
    calculate_park_target,
    inject_timelapse_gcode,
)


class TestGCodeInjector(unittest.TestCase):
    def test_binary_bgcode_detection(self):
        self.assertTrue(is_binary_bgcode(b"GCDE\x01\x00\x00\x00binarypayload"))
        self.assertFalse(is_binary_bgcode(b"; generated by OrcaSlicer\nG28\n"))
        self.assertFalse(is_binary_bgcode(b""))
        self.assertFalse(is_binary_bgcode(None))

    def test_bed_boundary_parsing(self):
        gcode = "; generated by OrcaSlicer\n; bed_shape = 0x0,250x0,250x210,0x210\nG28\n"
        max_x, max_y = parse_bed_boundaries(gcode)
        self.assertEqual(max_x, 250.0)
        self.assertEqual(max_y, 210.0)

    def test_bed_boundary_fallback(self):
        gcode = "; no bed header present\nG28\n"
        max_x, max_y = parse_bed_boundaries(gcode)
        self.assertEqual(max_x, 250.0)
        self.assertEqual(max_y, 210.0)

    def test_bed_boundary_printable_area_variant(self):
        gcode = "; generated by OrcaSlicer\n; printable_area = 0x0, 180x0, 180x180, 0x180\nG28\n"
        max_x, max_y = parse_bed_boundaries(gcode)
        self.assertEqual(max_x, 180.0)
        self.assertEqual(max_y, 180.0)

    def test_park_target_clamping_mk4(self):
        target_x, target_y = calculate_park_target(240.0, 210.0, 250.0, 210.0)
        self.assertEqual(target_x, 240.0)
        self.assertEqual(target_y, 200.0)

    def test_park_target_clamping_mini(self):
        target_x, target_y = calculate_park_target(240.0, 210.0, 180.0, 180.0)
        self.assertEqual(target_x, 170.0)
        self.assertEqual(target_y, 170.0)

    def test_park_target_clamping_xl(self):
        target_x, target_y = calculate_park_target(350.0, 350.0, 360.0, 360.0)
        self.assertEqual(target_x, 350.0)
        self.assertEqual(target_y, 350.0)

    def test_layer_change_injection(self):
        gcode = (
            "; generated by OrcaSlicer\n"
            "; bed_shape = 0x0,250x0,250x210,0x210\n"
            "G1 Z0.2 F1000\n"
            ";AFTER_LAYER_CHANGE\n"
            ";[layer_z]\n"
            "G1 X50 Y50 E1.0\n"
            ";AFTER_LAYER_CHANGE\n"
            ";[layer_z]\n"
            "G1 X60 Y60 E2.0\n"
        )
        config = {
            "parkX": 240.0,
            "parkY": 210.0,
            "zHopHeight": 0.4,
            "settleTime": 300,
            "captureTime": 1200,
        }
        modified, count = inject_timelapse_gcode(gcode, config)
        self.assertEqual(count, 2)
        self.assertIn("M220 S99", modified)
        self.assertIn("G1 X240.0 Y200.0 F9000", modified)
        self.assertIn("M83 ; Strict relative extrusion", modified)
        self.assertIn("G1 F9000 ; Restore normal travel feedrate", modified)
        self.assertIn("M220 S100", modified)

    def test_layer_change_fallback_marker(self):
        gcode = (
            "; generated by OrcaSlicer\n"
            "; bed_shape = 0x0,250x0,250x210,0x210\n"
            "G1 Z0.2 F1000\n"
            ";LAYER_CHANGE\n"
            ";Z:0.2\n"
            "G1 X50 Y50 E1.0\n"
        )
        config = {
            "parkX": 240.0,
            "parkY": 200.0,
            "zHopHeight": 0.4,
            "settleTime": 300,
            "captureTime": 1200,
        }
        modified, count = inject_timelapse_gcode(gcode, config)
        self.assertEqual(count, 1)
        self.assertIn("M220 S99", modified)

    def test_crlf_preservation(self):
        gcode = "; bed_shape = 0x0,250x0,250x210,0x210\r\n;AFTER_LAYER_CHANGE\r\nG1 X10 Y10\r\n"
        modified, count = inject_timelapse_gcode(gcode, {"parkX": 240.0, "parkY": 200.0})
        self.assertEqual(count, 1)
        self.assertIn("\r\n", modified)
        self.assertNotIn("\n\n", modified.replace("\r\n", "\n"))

    def test_duplicate_injection_guard(self):
        gcode = (
            "; generated by OrcaSlicer\n"
            ";AFTER_LAYER_CHANGE\n"
            "G1 X50 Y50 E1.0\n"
        )
        config = {"parkX": 240.0, "parkY": 200.0}
        modified, count = inject_timelapse_gcode(gcode, config)
        self.assertEqual(count, 1)

        # Running again on already modified gcode should not double-inject
        remodified, recount = inject_timelapse_gcode(modified, config)
        self.assertEqual(recount, 0)
        self.assertEqual(remodified, modified)


if __name__ == "__main__":
    unittest.main()
